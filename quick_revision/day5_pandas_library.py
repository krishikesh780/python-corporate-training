# ==================================================
# 1️⃣ iterrows() – Pandas
# ==================================================

# Definition:
# iterrows() DataFrame ki har row ko (index, Series) ke form me deta hai

# Syntax:
# for idx, row in df.iterrows():
#     print(row['column'])

# Key Points:
# - row = Pandas Series
# - Column access: row['col']
# - Data type change ho sakta hai
# - Slow (har row pe Series banti hai)

# Pros:
# - Easy to read
# - Dynamic column access
# - Beginners friendly

# Cons:
# - Slow
# - Memory heavy
# - Large data ke liye unsafe

# Use when:
# - Small data (< 5k rows)
# - Debugging / learning
# - One-time scripts


# ==================================================
# 2️⃣ itertuples() – Pandas
# ==================================================

# Definition:
# itertuples() DataFrame ki har row ko namedtuple ke form me deta hai

# Syntax:
# for row in df.itertuples():
#     print(row.column)

# Key Points:
# - row = namedtuple (immutable)
# - Column access: row.col
# - Data type preserved
# - Very fast

# Pros:
# - 5–20x faster than iterrows
# - Low memory usage
# - Production ready

# Cons:
# - Dynamic column access difficult
# - Invalid column names issue

# Use when:
# - Large dataset
# - Automation / production
# - Performance matters


# ==================================================
# 3️⃣ Generator – Python Core
# ==================================================

# Definition:
# Generator ek function hota hai jo yield se
# values ek-ek karke (on-demand) deta hai

# Example:
def number_gen():
    for i in range(3):
        yield i

# Key Points:
# - Lazy evaluation
# - One value at a time
# - Very low memory usage
# - Pause & resume execution

# Pros:
# - Best for large data
# - Streaming friendly
# - Clean abstraction

# Cons:
# - One-time iteration
# - Debug thoda hard

# Use when:
# - Large data
# - Streaming
# - ETL / AI / logs pipelines


# ==================================================
# 4️⃣ iterrows vs itertuples vs Generator
# ==================================================

# iterrows     -> Slow, high memory, avoid in production
# itertuples   -> Fast, low memory, production ready
# Generator    -> Fastest, streaming, best for large data




# ==================================================
# 5️⃣ Best Design Pattern (Recommended)
# ==================================================

def row_generator(df):
    for row in df.itertuples():
        yield row

# Use:
for row in row_generator(df):
    process(row)

# ✔ Fast
# ✔ Clean
# ✔ Scalable


